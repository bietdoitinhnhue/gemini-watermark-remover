export function getPageUrl(page, locale) {
    return `${SITE_ORIGIN}${PAGE_METADATA[page][locale].path}`;
}

export function buildPageJsonLd(page, locale) {
    const meta = PAGE_METADATA[page][locale];
    const url = getPageUrl(page, locale);
    const language = locale === 'vi' ? 'vi-VN' : 'en';
    const faqs = PAGE_FAQS[page][locale];

    return [
        {
            '@context': 'https://schema.org',
            '@type': 'WebPage',
            '@id': `${url}#webpage`,
            url,
            name: meta.title,
            description: meta.description,
            inLanguage: language,
            isPartOf: {
                '@type': 'WebSite',
                name: 'GrowthAutomationX',
                url: 'https://growthautomationx.com'
            },
            primaryImageOfPage: meta.ogImage
        },
        {
            '@context': 'https://schema.org',
            '@type': 'SoftwareApplication',
            name: meta.name,
            applicationCategory: 'MultimediaApplication',
            operatingSystem: 'Web browser',
            url,
            image: meta.ogImage,
            description: meta.appDescription,
            inLanguage: language,
            browserRequirements: 'Latest Chrome or Edge recommended for media processing.',
            publisher: {
                '@type': 'Organization',
                name: 'GrowthAutomationX',
                url: 'https://growthautomationx.com'
            }
        },
        {
            '@context': 'https://schema.org',
            '@type': 'FAQPage',
            mainEntity: faqs.map(([name, text]) => ({
                '@type': 'Question',
                name,
                acceptedAnswer: {
                    '@type': 'Answer',
                    text
                }
            }))
        }
    ];
}
